"""Evidence-based storage inventory and guarded cleanup.

This module deliberately owns a small, explicit set of application roots.  It
does not scan a user's drive and it never treats a filename by itself as proof
that an item is disposable.  Every item is classified from its root ownership,
the current application references, and the regeneration contract recorded in
``CATEGORY_DEFINITIONS``.
"""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import threading
from pathlib import Path
from typing import Any, Iterable, Mapping


SAFE_TO_DELETE = "SAFE_TO_DELETE"
REVIEW_BEFORE_DELETE = "REVIEW_BEFORE_DELETE"
PROTECTED = "PROTECTED"
UNKNOWN = "UNKNOWN"

_ACTIVE_STATES = {
    "PREPARING", "PROCESSING", "PAUSE_REQUESTED", "PAUSED",
    "INTERRUPTED", "RECOVERABLE",
}

